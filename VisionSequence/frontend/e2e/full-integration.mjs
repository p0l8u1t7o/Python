/** 模組 integration：整合頁五個分頁（S）。 */
import { BASE } from './full-lib.mjs'

export async function run(h) {
  await h.loginAdmin()
  const context = await h.newContext({ token: h.token })
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  const page = await h.newPage(context, '[integration]')
  const demo = h.demoFlow()

  await h.step('S01 資訊列', async () => {
    await page.goto(`${BASE}/integration`)
    await page.getByTestId('integration-info').waitFor({ timeout: 10000 })
    const txt = await page.getByTestId('integration-info').innerText()
    await h.shot(page, 'integration-http')
    h.item('S01', txt.includes('HTTP 位址') && /TCP：\s*\S+:\d+/.test(txt) && txt.includes('監聽中') && txt.includes('API 金鑰') && txt.includes('不需要') && /執行緒：\d+/.test(txt) && /逾時（秒）：\d+/.test(txt), `info=${txt.replace(/\n/g, '|')}`)
  })

  await h.step('S02 S03 HTTP 測試與片段', async () => {
    const httpTab = page.getByTestId('integration-http')
    await page.getByTestId('http-flow').selectOption(String(demo.id))
    const mode = httpTab.locator('select').nth(1)
    await mode.selectOption('file')
    const fileInput = (await page.getByTestId('http-file').count()) === 1
    await mode.selectOption('json')
    const code = () => httpTab.locator('pre').first().innerText()
    const c1 = await code()
    await page.getByTestId('http-context').fill('{"lot": "A1"}')
    const c2 = await code()
    await httpTab.getByRole('tab', { name: 'Python' }).click()
    const py = await code()
    await httpTab.getByRole('tab', { name: 'C#' }).click()
    const cs = await code()
    await httpTab.getByRole('tab', { name: 'curl' }).click()
    await page.getByTestId('http-context').fill('{bad json')
    await page.getByTestId('http-send').click()
    const tInvalid = await h.toast(page, /context 不是合法 JSON/)
    await page.getByTestId('http-context').fill('{}')
    const waitCb = httpTab.getByRole('checkbox', { name: /等待結果/ })
    await waitCb.uncheck()
    const timeoutDisabled = await httpTab.getByLabel('逾時（秒）').isDisabled()
    await waitCb.check()
    await page.getByTestId('http-send').click()
    await page.getByTestId('http-result').waitFor({ timeout: 30000 })
    await page.waitForTimeout(500)
    const result = page.getByTestId('http-result')
    const rtxt = await result.innerText()
    const status = await result.locator('span.rounded-full').first().innerText()
    const preShown = (await result.locator('pre').count()) === 1
    await result.getByRole('button', { name: /回應/ }).click()
    const preHidden = (await result.locator('pre').count()) === 0
    await result.getByRole('button', { name: /回應/ }).click()
    const imgs = await result.locator('figure img').count()
    const imgOk = imgs > 0 ? await result.locator('figure img').first().evaluate((el) => el.complete && el.naturalWidth > 0) : false
    await result.getByRole('button', { name: '複製' }).click()
    const copied = await result.getByRole('button', { name: '已複製' }).waitFor({ timeout: 2000 }).then(() => 1).catch(() => 0)
    await h.shot(page, 'integration-http-result')
    h.item('S02', fileInput && Boolean(tInvalid) && timeoutDisabled && status === '200' && /耗時：\d+ ms/.test(rtxt) && preShown && preHidden && imgs > 0 && imgOk && copied === 1, `file=${fileInput} invalid=${tInvalid} timeoutDis=${timeoutDisabled} status=${status} pre=${preShown}/${preHidden} imgs=${imgs} imgOk=${imgOk} copied=${copied}`)
    const snippetCopy = httpTab.locator('.relative').last().getByRole('button', { name: '複製' })
    await snippetCopy.click()
    const sc = await httpTab.locator('.relative').last().getByRole('button', { name: '已複製' }).waitFor({ timeout: 2000 }).then(() => 1).catch(() => 0)
    h.item('S03', c1.startsWith('curl') && c2.includes('"lot": "A1"') && c1 !== c2 && py.includes('import requests') && cs.includes('HttpClient') && sc === 1, `curl=${c1.slice(0, 30)} ctx=${c2.includes('"lot": "A1"')} py=${py.includes('import requests')} cs=${cs.includes('HttpClient')} copied=${sc}`)
  })

  await h.step('S04 TCP', async () => {
    await page.getByRole('tab', { name: 'TCP 測試' }).click()
    await page.evaluate(() => localStorage.removeItem('vs.tcpHistory'))
    const tab = page.getByTestId('integration-tcp')
    const chips = await tab.locator('button.font-mono').allInnerTexts()
    await tab.locator('button.font-mono', { hasText: 'LIST' }).first().click()
    const cmdVal = await page.getByTestId('tcp-command').inputValue()
    await page.getByTestId('tcp-command').fill('PING')
    await page.getByTestId('tcp-command').press('Enter')
    await page.getByTestId('tcp-result').waitFor({ timeout: 15000 })
    await page.waitForTimeout(300)
    const r1 = await page.getByTestId('tcp-result').innerText()
    await page.getByTestId('tcp-command').fill(`RUN ${demo.id}`)
    await page.getByTestId('tcp-send').click()
    await page.waitForTimeout(3000)
    const r2 = await page.getByTestId('tcp-result').innerText()
    const hist = page.getByTestId('tcp-history')
    const histItems = await hist.locator('li').allInnerTexts()
    await hist.locator('li').filter({ hasText: 'PING' }).getByRole('button', { name: '重送' }).click()
    await page.waitForTimeout(1200)
    const r3 = await page.getByTestId('tcp-result').innerText()
    await h.shot(page, 'integration-tcp')
    await tab.getByRole('button', { name: '清除歷史' }).click()
    const histGone = (await page.getByTestId('tcp-history').count()) === 0
    const stored = await page.evaluate(() => localStorage.getItem('vs.tcpHistory'))
    h.item('S04', chips.length >= 5 && cmdVal.startsWith('LIST') && r1.includes('路徑：tcp') && r1.includes('PING') && /"status"/.test(r2) && r2.includes(`RUN ${demo.id}`) && histItems.length === 2 && histItems[0].includes('RUN') && r3.startsWith('PING') && histGone && stored === null, `chips=${chips.join(',')} cmd=${cmdVal} r1=${r1.slice(0, 60).replace(/\n/g, '|')} r2=${r2.slice(0, 80).replace(/\n/g, '|')} hist=${histItems.join('|').replace(/\n/g, ' ')} resend=${r3.slice(0, 20)} gone=${histGone} stored=${stored}`)
  })

  await h.step('S05 事件監看', async () => {
    await page.getByRole('tab', { name: '事件監看' }).click()
    await page.getByTestId('events-table').waitFor()
    await page.waitForTimeout(1000)
    const empty = (await page.getByTestId('events-table').innerText()).includes('還沒有事件')
    const connected = (await page.getByTestId('integration-events').innerText()).includes('已連線')
    await h.api.post(`/vision/flows/${demo.id}/run?wait=1`, { context: null, wait: true })
    await page.waitForTimeout(1500)
    const rows = await page.getByTestId('event-row').count()
    const types = await page.getByTestId('event-row').locator('td:nth-child(2)').allInnerTexts()
    const finished = page.getByTestId('event-row').filter({ hasText: 'run_finished' }).first()
    const ftxt = await finished.innerText()
    await h.shot(page, 'integration-events')
    await page.getByTestId('events-pause').click()
    const paused = (await page.getByTestId('events-pause').innerText()).includes('繼續')
    await h.api.post(`/vision/flows/${demo.id}/run?wait=1`, { context: null, wait: true })
    await page.waitForTimeout(1500)
    const rowsPaused = await page.getByTestId('event-row').count()
    await page.getByTestId('events-pause').click()
    await h.api.post(`/vision/flows/${demo.id}/run?wait=1`, { context: null, wait: true })
    await page.waitForTimeout(1500)
    const rowsResumed = await page.getByTestId('event-row').count()
    await page.getByTestId('integration-events').getByRole('button', { name: '清除' }).click()
    const clearedEmpty = (await page.getByTestId('events-table').innerText()).includes('還沒有事件')
    h.item('S05', empty && connected && rows >= 2 && types.includes('run_finished') && types.includes('run_started') && /OK|NG/.test(ftxt) && ftxt.includes(demo.name) && /\d+/.test(ftxt) && paused && rowsPaused === rows && rowsResumed > rows && clearedEmpty, `empty=${empty} connected=${connected} rows=${rows} types=${types.join(',')} finished=${ftxt.replace(/\n/g, '|').slice(0, 80)} paused=${paused} rowsPaused=${rowsPaused} resumed=${rowsResumed} cleared=${clearedEmpty}`)
  })

  await h.step('S06 鎖定分頁', async () => {
    await page.getByRole('tab', { name: '鎖定' }).click()
    const tab = page.getByTestId('integration-lock')
    const t0 = await tab.innerText()
    const codes = await tab.locator('pre').count()
    await h.api.post('/vision/lock', { reason: 'E2E 測試鎖', ttl_s: 600 })
    await page.waitForTimeout(1500)
    const t1 = await tab.innerText()
    await h.shot(page, 'integration-lock')
    await h.api.del('/vision/lock')
    await page.waitForTimeout(1200)
    const t2 = await tab.innerText()
    const link = (await tab.getByRole('link', { name: '到設定頁鎖定／解鎖' }).count()) === 1
    h.item('S06', t0.includes('未鎖定') && codes === 3 && t1.includes('已鎖定') && t1.includes('admin') && t1.includes('E2E 測試鎖') && t1.includes('自動解鎖') && t2.includes('未鎖定') && link, `t0=${t0.includes('未鎖定')} codes=${codes} locked=${t1.slice(0, 120).replace(/\n/g, '|')} unlocked=${t2.includes('未鎖定')} link=${link}`)
  })

  await h.step('S07 回傳格式', async () => {
    await page.getByRole('tab', { name: '回傳格式' }).click()
    const tab = page.getByTestId('integration-format')
    const tables = await tab.locator('table').count()
    const rows1 = await tab.locator('table').first().locator('tbody tr').count()
    const rows2 = await tab.locator('table').last().locator('tbody tr').count()
    const txt = await tab.innerText()
    await h.shot(page, 'integration-format', { full: true })
    h.item('S07', tables === 2 && rows1 === 10 && rows2 === 12 && txt.includes('hole_count') && txt.includes('engine_locked') && txt.includes('423'), `tables=${tables} rows=${rows1}/${rows2}`)
  })

  await h.step('S08 深連結', async () => {
    const urlHasTab = page.url().includes('tab=format')
    await page.goto(`${BASE}/integration?tab=tcp`)
    await page.getByTestId('integration-tcp').waitFor({ timeout: 8000 })
    const sel = await page.getByRole('tab', { name: 'TCP 測試' }).getAttribute('aria-selected')
    h.item('S08', urlHasTab && sel === 'true', `urlHasTab=${urlHasTab} tcpSelected=${sel}`)
  })

  await context.close()
}
