/** 模組 connections：連線頁（Z）。建立 E2E 開頭的連線，結束時刪。 */
import { BASE, WORKER } from './full-lib.mjs'
import { ensureWorker } from './full-teach.mjs'

export async function run(h) {
  await h.loginAdmin()
  await ensureWorker(h)
  for (const c of (await h.api.get('/vision/connections'))?.items ?? []) if (/^E2E /.test(c.name)) await h.api.del(`/vision/connections/${c.id}`)
  const context = await h.newContext({ token: h.token })
  const page = await h.newPage(context, '[connections]')
  const row = (name) => page.locator('main tbody tr').filter({ hasText: name })
  const dlg = () => h.dialog(page)
  const openPage = async () => {
    await page.goto(`${BASE}/connections`)
    await page.getByTestId('conn-create').waitFor({ timeout: 15000 })
    await page.waitForLoadState('networkidle')
    await page.waitForTimeout(300)
  }

  await h.step('Z01 頁面', async () => {
    await openPage()
    const main = await page.locator('main').innerText()
    const link = await page.locator('main').getByRole('link', { name: /整合頁「PLC 輸出」/ }).getAttribute('href')
    const head = (await page.locator('main thead').innerText().catch(() => '')).replace(/\n/g, '|')
    const empty = main.includes('還沒有連線')
    await h.shot(page, 'connections')
    h.item('Z01', main.includes('連線') && link === '/integration?tab=plc' && (empty || ['名稱', '種類', '設定', '狀態', '啟用', '操作'].every((k) => head.includes(k))), `link=${link} head=${head} empty=${empty}`)
  })

  await h.step('Z02 新增 Modal 各種 kind', async () => {
    await page.getByTestId('conn-create').click()
    await dlg().waitFor()
    const kindOpts = await page.getByTestId('conn-kind').locator('option').allInnerTexts()
    const kind0 = await page.getByTestId('conn-kind').inputValue()
    const labelsOf = async () => dlg().locator('label').allInnerTexts()
    const dio = await labelsOf()
    const channels = await dlg().getByLabel('通道').inputValue()
    await page.getByTestId('conn-kind').selectOption('modbus_tcp')
    const modbus = await labelsOf()
    const host = await dlg().getByLabel('主機').inputValue()
    const port = await dlg().getByLabel('埠').inputValue()
    const wordOpts = await dlg().getByLabel('字組順序（32 位元）').locator('option').allInnerTexts()
    await dlg().getByLabel('主機').fill('10.0.0.9')
    await page.getByTestId('conn-kind').selectOption('tcp_client')
    const tcp = await labelsOf()
    const tcpHost = await dlg().getByLabel('主機').inputValue()
    const tcpPort = await dlg().getByLabel('埠').inputValue()
    const waitReply = (await dlg().getByRole('checkbox', { name: '等待回覆' }).count()) === 1
    const newline = await dlg().getByLabel('結尾字元').inputValue()
    await page.getByTestId('conn-kind').selectOption('plugin')
    const plugin = await labelsOf()
    await h.shot(page, 'connections-form-plugin')
    await page.getByTestId('conn-kind').selectOption('dio_sim')
    await page.getByTestId('conn-save').click()
    const tName = await h.toast(page, /請輸入名稱/)
    h.item('Z02', kindOpts.length === 4 && kind0 === 'dio_sim' && dio.some((l) => l.includes('通道')) && channels === 'DO0,DO1,OK,NG' && ['主機', '埠', 'Unit ID', '逾時', '字組順序'].every((k) => modbus.some((l) => l.includes(k))) && host === '127.0.0.1' && port === '502' && wordOpts.length === 2 && ['主機', '埠', '逾時', '訊息範本', '結尾字元', '等待回覆'].every((k) => tcp.some((l) => l.includes(k))) && tcpHost === '127.0.0.1' && tcpPort === '9000' && waitReply && newline === '\\n' && plugin.some((l) => l.includes('類別路徑')) && Boolean(tName), `kinds=${kindOpts.join('/')} kind0=${kind0} dio=${dio.join('|')} channels=${channels} modbus=${modbus.join('|')} host=${host} port=${port} word=${wordOpts.join('/')} tcp=${tcp.join('|')} tcpHost=${tcpHost}/${tcpPort} waitReply=${waitReply} newline=${newline} plugin=${plugin.join('|')} tName=${tName}`)
  })

  await h.step('Z03 建立 dio_sim 與 modbus', async () => {
    await page.getByTestId('conn-name-input').fill('E2E sim')
    await dlg().getByLabel('通道').fill('DO0, DO1, OK, NG, DONE')
    await page.getByTestId('conn-save').click()
    const t1 = await h.toast(page, /已建立連線/)
    await page.waitForTimeout(500)
    const r = row('E2E sim')
    const kindBadge = await r.locator('span.rounded-full').first().innerText()
    const cfg = await r.locator('code').first().innerText()
    await page.getByTestId('conn-create').click()
    await dlg().waitFor()
    await page.getByTestId('conn-name-input').fill('E2E modbus')
    await page.getByTestId('conn-kind').selectOption('modbus_tcp')
    await dlg().getByLabel('埠').fill('1')
    await dlg().getByLabel('逾時（秒）').fill('0.3')
    await h.shot(page, 'connections-form-modbus')
    await page.getByTestId('conn-save').click()
    const t2 = await h.toast(page, /已建立連線/)
    await page.waitForTimeout(500)
    const list = (await h.api.get('/vision/connections')).items
    const modbus = list.find((c) => c.name === 'E2E modbus')
    await h.shot(page, 'connections-list')
    h.item('Z03', Boolean(t1) && kindBadge.includes('模擬 DIO') && cfg.includes('DONE') && Boolean(t2) && modbus?.kind === 'modbus_tcp' && modbus.config.port === 1 && modbus.config.timeout_s === 0.3 && modbus.config.word_order === 'big', `t1=${t1} badge=${kindBadge} cfg=${cfg} t2=${t2} modbus=${JSON.stringify(modbus?.config)}`)
  })

  await h.step('Z04 測試連線', async () => {
    await row('E2E sim').getByTestId('conn-test').click()
    const t1 = await h.toast(page, /連線成功/)
    await page.waitForTimeout(600)
    const status = await row('E2E sim').locator('td').nth(3).innerText()
    await row('E2E modbus').getByTestId('conn-test').click()
    const t2 = await h.toast(page, /連線失敗：/, 15000)
    await page.waitForTimeout(300)
    await h.shot(page, 'connections-tested')
    h.item('Z04', Boolean(t1) && status.includes('已連線') && Boolean(t2), `t1=${t1} status=${status.replace(/\n/g, ' ').slice(0, 60)} t2=${t2}`)
  })

  await h.step('Z05 手動寫入', async () => {
    await row('E2E sim').getByTestId('conn-write').click()
    await dlg().waitFor()
    const title = await dlg().locator('h2').innerText()
    const preset = await page.getByTestId('conn-write-values').inputValue()
    await page.getByTestId('conn-write-values').fill('{bad')
    await page.getByTestId('conn-write-send').click()
    const tBad = await h.toast(page, /values 必須是 JSON 物件/)
    await page.waitForTimeout(1200)
    await page.getByTestId('conn-write-values').fill('[1,2]')
    await page.getByTestId('conn-write-send').click()
    const tArr = await h.toast(page, /values 必須是 JSON 物件/)
    await page.getByTestId('conn-write-values').fill('{"DO0": 1, "OK": 1, "DONE": 1}')
    await page.getByTestId('conn-write-send').click()
    const tOk = await h.toast(page, /已寫入 3 筆/)
    await page.getByTestId('connection-result').waitFor()
    const res = await page.getByTestId('connection-result').innerText()
    await h.shot(page, 'connections-write')
    await page.keyboard.press('Escape')
    await h.waitGone(dlg())
    await row('E2E modbus').getByTestId('conn-write').click()
    await dlg().waitFor()
    const presetModbus = await page.getByTestId('conn-write-values').inputValue()
    await page.getByTestId('conn-write-send').click()
    const tFail = await h.toast(page, /寫入失敗：/, 15000)
    await page.getByTestId('connection-result').waitFor()
    const failRed = await page.getByTestId('connection-result').evaluate((el) => el.className.includes('bg-critical-soft'))
    await h.shot(page, 'connections-write-fail')
    await page.keyboard.press('Escape')
    await h.waitGone(dlg())
    h.item('Z05', title.includes('手動寫入：E2E sim') && preset === '{"DO0":1}' && Boolean(tBad) && Boolean(tArr) && Boolean(tOk) && res.includes('"ok": true') && presetModbus.includes('coil:0') && Boolean(tFail) && failRed, `title=${title} preset=${preset} bad=${tBad} arr=${tArr} ok=${tOk} res=${res.replace(/\s+/g, ' ').slice(0, 60)} presetModbus=${presetModbus} fail=${tFail} red=${failRed}`)
  })

  await h.step('Z06 狀態檢視', async () => {
    await row('E2E sim').getByRole('button', { name: '狀態檢視' }).click()
    await dlg().waitFor()
    await page.getByTestId('conn-state-table').waitFor({ timeout: 5000 })
    const table = await page.getByTestId('conn-state-table').innerText()
    const title = await dlg().locator('h2').innerText()
    await h.api.post(`/vision/connections/${(await h.api.get('/vision/connections')).items.find((c) => c.name === 'E2E sim').id}/write`, { values: { DO1: 1 } })
    await dlg().getByRole('button', { name: '重新整理' }).click()
    await page.waitForTimeout(800)
    const table2 = await page.getByTestId('conn-state-table').innerText()
    await h.shot(page, 'connections-state')
    await page.keyboard.press('Escape')
    await h.waitGone(dlg())
    await row('E2E modbus').getByRole('button', { name: '狀態檢視' }).click()
    await dlg().waitFor()
    await page.waitForTimeout(1500)
    const addr = (await dlg().getByLabel('位址').count()) === 1
    await dlg().getByLabel('位址').fill('coil:0')
    await dlg().getByLabel('位址').press('Enter')
    await page.getByTestId('connection-result').waitFor({ timeout: 15000 })
    await page.waitForTimeout(500)
    const res = await page.getByTestId('connection-result').innerText()
    const noTable = (await page.getByTestId('conn-state-table').count()) === 0
    await page.keyboard.press('Escape')
    await h.waitGone(dlg())
    h.item('Z06', title.includes('狀態：E2E sim') && /DO0\s+1/.test(table) && /OK\s+1/.test(table) && /DONE\s+1/.test(table) && /DO1\s+1/.test(table2) && addr && res.includes('"ok": false') && noTable, `title=${title} table=${table.replace(/\n/g, ' ')} table2=${table2.replace(/\n/g, ' ')} addr=${addr} res=${res.replace(/\s+/g, ' ').slice(0, 80)} noTable=${noTable}`)
  })

  await h.step('Z07 編輯', async () => {
    await row('E2E sim').getByRole('button', { name: '編輯' }).click()
    await dlg().waitFor()
    const title = await dlg().locator('h2').innerText()
    const name = await page.getByTestId('conn-name-input').inputValue()
    const kind = await page.getByTestId('conn-kind').inputValue()
    const channels = await dlg().getByLabel('通道').inputValue()
    await dlg().getByLabel('通道').fill('DO0,DO1,OK,NG,DONE,BUSY')
    await page.getByTestId('conn-save').click()
    const t = await h.toast(page, /已更新連線/)
    await page.waitForTimeout(500)
    const cfg = await row('E2E sim').locator('code').first().innerText()
    // 同名 → 409
    await row('E2E modbus').getByRole('button', { name: '編輯' }).click()
    await dlg().waitFor()
    await page.getByTestId('conn-name-input').fill('E2E sim')
    const release = h.allowStatus(/409 PATCH .*\/connections\/\d+/)
    await page.getByTestId('conn-save').click()
    const tDup = await h.toast(page, /已有同名連線/)
    release()
    await page.keyboard.press('Escape')
    await h.waitGone(dlg())
    h.item('Z07', title === '編輯' && name === 'E2E sim' && kind === 'dio_sim' && channels === 'DO0,DO1,OK,NG,DONE' && Boolean(t) && cfg.includes('BUSY') && Boolean(tDup), `title=${title} name=${name} kind=${kind} channels=${channels} t=${t} cfg=${cfg} dup=${tDup}`)
  })

  await h.step('Z08 啟用開關', async () => {
    const sw = row('E2E sim').getByRole('switch')
    await sw.click()
    await page.waitForTimeout(600)
    const off = (await h.api.get('/vision/connections')).items.find((c) => c.name === 'E2E sim').is_enabled === false
    const ui = await sw.getAttribute('aria-checked')
    await sw.click()
    await page.waitForTimeout(600)
    const on = (await h.api.get('/vision/connections')).items.find((c) => c.name === 'E2E sim').is_enabled === true
    h.item('Z08', off && ui === 'false' && on, `off=${off} ui=${ui} on=${on}`)
  })

  await h.step('Z10 worker 視角', async () => {
    const wtoken = await h.login(WORKER)
    const wctx = await h.newContext({ token: wtoken })
    const worker = await h.newPage(wctx, '[connections-worker]')
    await worker.goto(`${BASE}/connections`)
    await worker.getByTestId('conn-create').waitFor({ timeout: 15000 })
    await worker.waitForLoadState('networkidle')
    await worker.waitForTimeout(300)
    const createDis = await worker.getByTestId('conn-create').isDisabled()
    const title = await worker.getByTestId('conn-create').locator('xpath=..').getAttribute('title')
    const r = worker.locator('main tbody tr').filter({ hasText: 'E2E sim' })
    const testDis = await r.getByTestId('conn-test').isDisabled()
    const writeDis = await r.getByTestId('conn-write').isDisabled()
    const editDis = await r.getByRole('button', { name: '編輯' }).isDisabled()
    const delDis = await r.getByRole('button', { name: '刪除' }).isDisabled()
    const swDis = await r.getByRole('switch').isDisabled()
    await r.getByRole('button', { name: '狀態檢視' }).click()
    await h.dialog(worker).waitFor()
    const stateOk = (await worker.getByTestId('conn-state-table').waitFor({ timeout: 5000 }).then(() => 1).catch(() => 0)) === 1
    await h.shot(worker, 'connections-worker')
    await worker.keyboard.press('Escape')
    await wctx.close()
    h.item('Z10', createDis && title?.includes('只有管理員') && testDis && writeDis && editDis && delDis && swDis && stateOk, `create=${createDis} title=${title} test=${testDis} write=${writeDis} edit=${editDis} del=${delDis} sw=${swDis} state=${stateOk}`)
  })

  await h.step('Z09 刪除', async () => {
    await row('E2E modbus').getByRole('button', { name: '刪除' }).click()
    await dlg().waitFor()
    const msg = await dlg().innerText()
    await dlg().getByRole('button', { name: '刪除', exact: true }).click()
    const t = await h.toast(page, /已刪除連線/)
    await page.waitForTimeout(500)
    const gone = (await row('E2E modbus').count()) === 0
    h.item('Z09', msg.includes('E2E modbus') && msg.includes('write_plc') && Boolean(t) && gone, `msg=${msg.replace(/\n/g, ' ').slice(0, 80)} t=${t} gone=${gone}`)
  })

  await h.step('Z11 空狀態與錯誤狀態', async () => {
    await page.route('**/api/vision/connections', (route) => (route.request().method() === 'GET' ? route.fulfill({ status: 200, contentType: 'application/json', body: '{"items":[]}' }) : route.continue()))
    await page.goto(`${BASE}/connections`)
    await page.getByTestId('conn-create').waitFor({ timeout: 15000 })
    await page.waitForTimeout(600)
    const empty = (await page.locator('main').innerText()).includes('還沒有連線')
    await h.shot(page, 'connections-empty')
    await page.unroute('**/api/vision/connections')
    let fail = true
    const release = h.allowStatus(/500 GET .*\/connections/)
    await page.route('**/api/vision/connections', (route) => (route.request().method() === 'GET' && fail ? route.fulfill({ status: 500, contentType: 'application/json', body: '{"detail":"連線列表壞掉"}' }) : route.continue()))
    await page.goto(`${BASE}/connections`)
    await page.waitForTimeout(1500)
    const err = await page.locator('main').innerText()
    fail = false
    await page.locator('main').getByRole('button', { name: '重試' }).click()
    await page.waitForTimeout(1000)
    const recovered = (await row('E2E sim').count()) === 1
    await page.unroute('**/api/vision/connections')
    release()
    h.item('Z11', empty && err.includes('連線列表壞掉') && recovered, `empty=${empty} err=${err.slice(0, 80).replace(/\n/g, '|')} recovered=${recovered}`)
  })

  await h.step('Z12 1280 與深色', async () => {
    const small = await h.newContext({ token: h.token, viewport: { width: 1280, height: 800 } })
    const sp = await h.newPage(small, '[connections-1280]')
    await sp.goto(`${BASE}/connections`)
    await sp.getByTestId('conn-create').waitFor({ timeout: 15000 })
    await sp.waitForLoadState('networkidle')
    await sp.waitForTimeout(400)
    const info = await sp.evaluate(() => ({ sw: document.documentElement.scrollWidth, cw: document.documentElement.clientWidth }))
    await h.shot(sp, 'connections-1280')
    await small.close()
    const dark = await h.newContext({ token: h.token, colorScheme: 'dark' })
    await dark.addInitScript(() => localStorage.setItem('vs.theme', 'dark'))
    const dp = await h.newPage(dark, '[connections-dark]')
    await dp.goto(`${BASE}/connections`)
    await dp.getByTestId('conn-create').waitFor({ timeout: 15000 })
    await dp.waitForLoadState('networkidle')
    await dp.waitForTimeout(400)
    await dp.locator('main tbody tr').filter({ hasText: 'E2E sim' }).getByTestId('conn-write').click()
    await h.dialog(dp).waitFor()
    await h.shot(dp, 'connections-dark-write')
    const isDark = await dp.evaluate(() => document.documentElement.classList.contains('dark'))
    await dark.close()
    h.item('Z12', info.sw <= info.cw + 1 && isDark, `scroll=${info.sw}/${info.cw} dark=${isDark}`)
  })

  // 清掉 E2E sim（flowio 模組自己建自己的）
  for (const c of (await h.api.get('/vision/connections'))?.items ?? []) if (/^E2E /.test(c.name)) await h.api.del(`/vision/connections/${c.id}`)
  await context.close()
}
